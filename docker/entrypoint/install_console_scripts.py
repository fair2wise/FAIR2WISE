"""Install the ``[project.scripts]`` console commands of ``pyproject.toml`` as launcher files.

The image does not ``pip install`` the project (its environment has no pip and the code runs from
``PYTHONPATH=/app``), so the ``f2w-*`` commands the operator docs name (``f2w-kg-adopt`` and the
others) did not exist inside the container (E2E finding 2026-11-06). This script reads the table
``pip`` would read and writes one small launcher per entry. ``pyproject.toml`` maps the package
``f2w`` onto the ``app/`` directory (``[tool.setuptools] package-dir``), so the module path is
rewritten the same way before import. No dependency beyond the standard library.

Usage (build time, as root)::

    python install_console_scripts.py --pyproject /app/pyproject.toml --bin /usr/local/bin \
        --python /opt/fair2wise/pixi/.pixi/envs/default/bin/python
"""

from __future__ import annotations

import argparse
from collections.abc import Mapping
from pathlib import Path
import re
import stat
import sys
import tomllib

_ENTRY = re.compile(r"^(?P<module>[A-Za-z_][\w.]*):(?P<attr>[A-Za-z_]\w*)$")
_NAME = re.compile(r"^[A-Za-z0-9][\w.-]*$")

LAUNCHER = """#!{python} -I
# Generated by docker/entrypoint/install_console_scripts.py from pyproject.toml [project.scripts].
import sys
from {module} import {attr} as _entry
sys.exit(_entry())
"""


def package_dir(pyproject: Mapping[str, object]) -> dict[str, str]:
    """The ``[tool.setuptools] package-dir`` map (``{"f2w": "app"}``), or ``{}``."""
    tool = pyproject.get("tool")
    if not isinstance(tool, Mapping):
        return {}
    setuptools = tool.get("setuptools")
    if not isinstance(setuptools, Mapping):
        return {}
    raw = setuptools.get("package-dir")
    if not isinstance(raw, Mapping):
        return {}
    return {str(k): str(v) for k, v in raw.items()}


def import_path(module: str, mapping: Mapping[str, str]) -> str:
    """Rewrite the distribution module path to the import path used with ``PYTHONPATH=/app``.

    ``f2w.modules.commands.run`` with ``{"f2w": "app"}`` becomes ``app.modules.commands.run``: the
    top-level package name is replaced by the directory it maps to (a plain directory name is a
    package name on the path; nested directories are not expected here).
    """
    head, _, rest = module.partition(".")
    target = mapping.get(head)
    if target is None:
        return module
    target = target.strip("/").replace("/", ".")
    return f"{target}.{rest}" if rest else target


def scripts(pyproject: Mapping[str, object]) -> dict[str, tuple[str, str]]:
    """``{command: (import_module, attribute)}`` for every ``[project.scripts]`` entry."""
    project = pyproject.get("project")
    if not isinstance(project, Mapping):
        return {}
    table = project.get("scripts")
    if not isinstance(table, Mapping):
        return {}
    mapping = package_dir(pyproject)
    out: dict[str, tuple[str, str]] = {}
    for name, spec in table.items():
        if not _NAME.match(str(name)):
            raise ValueError(f"invalid console script name {name!r}")
        match = _ENTRY.match(str(spec))
        if match is None:
            raise ValueError(f"invalid entry point {spec!r} for {name}")
        out[str(name)] = (import_path(match.group("module"), mapping), match.group("attr"))
    return out


def render(python: str, module: str, attr: str) -> str:
    """The launcher file text."""
    return LAUNCHER.format(python=python, module=module, attr=attr)


def install(pyproject_path: Path, bin_dir: Path, python: str) -> list[str]:
    """Write one launcher per script into ``bin_dir`` (mode 0755) and return the names written."""
    data = tomllib.loads(pyproject_path.read_text(encoding="utf-8"))
    entries = scripts(data)
    bin_dir.mkdir(parents=True, exist_ok=True)
    written: list[str] = []
    for name, (module, attr) in sorted(entries.items()):
        path = bin_dir / name
        path.write_text(render(python, module, attr), encoding="utf-8")
        path.chmod(stat.S_IRWXU | stat.S_IRGRP | stat.S_IXGRP | stat.S_IROTH | stat.S_IXOTH)
        written.append(name)
    return written


def main(argv: list[str] | None = None) -> int:
    """Command-line entry."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--pyproject", type=Path, required=True)
    parser.add_argument("--bin", type=Path, required=True)
    parser.add_argument("--python", required=True, help="interpreter the launchers run with")
    args = parser.parse_args(argv)
    names = install(args.pyproject, args.bin, args.python)
    sys.stdout.write(f"installed {len(names)} console script(s) into {args.bin}: {', '.join(names)}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
