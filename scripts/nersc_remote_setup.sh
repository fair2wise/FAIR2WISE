#!/usr/bin/env bash
set -euo pipefail

# Run on NERSC from repo root. Creates/updates the Python environment used by
# the Globus Compute endpoint worker.
#
# The environment is the locked pixi `default` environment (pixi.toml / pixi.lock, installed
# with --locked, so only hash-checked packages are installed). The scripts that follow
# (`source .venv/bin/activate`) keep working: this script writes $VENV_DIR/bin/activate as a
# small shim that activates the pixi environment. pixi must already be on PATH on the remote
# (the version in pixi.lock is 0.84.2; see https://pixi.sh/latest/installation/).

REPO_DIR="${1:-$(pwd)}"
VENV_DIR="${VENV_DIR:-.venv}"

cd "$REPO_DIR"

if ! command -v pixi >/dev/null 2>&1; then
  echo "Error: pixi is not on PATH. Install pixi (https://pixi.sh/latest/installation/) on the" >&2
  echo "remote host, then re-run this script. Dependencies are locked in pixi.lock." >&2
  exit 1
fi

pixi install --locked -e default

mkdir -p "$VENV_DIR/bin"
cat > "$VENV_DIR/bin/activate" <<SHIM
# Generated by scripts/nersc_remote_setup.sh: activates the locked pixi \`default\` environment.
eval "\$(pixi shell-hook -e default --manifest-path "$REPO_DIR/pixi.toml")"
SHIM

mkdir -p runs/hpc_extract/pdfs runs/hpc_extract/logs

echo "NERSC repo ready: $REPO_DIR"
echo "Activate with: source $REPO_DIR/$VENV_DIR/bin/activate"
